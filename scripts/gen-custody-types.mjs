// Generates everything the SDK derives from the vendored Ripple Custody specs
// (openapi/custody/ — layout in scripts/lib/custody-specs.mjs):
//
//   src/generated/custody.ts                  public API types (merged)
//   src/generated/custody-routes.ts           public operationId → route
//   src/generated/custody-internal.ts         internal API types (merged)
//   src/generated/custody-internal-routes.ts  internal operationId → route
//   src/generated/custody-capabilities.ts     per-version data for a pinned apiVersion
//   src/generated/custody-availability.ts     where each endpoint/operation is served
//   docs/custody-endpoints.md                 the same, for readers
//
// The two surfaces are merged and typed separately: they are disjoint APIs
// whose operationIds overlap (e.g. `getUsers`), so one `operations` map would
// silently drop operations.
//
// Run through `npm run typegen`, which also formats the output.

import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import openapiTS, { astToString } from 'openapi-typescript'

import {
  classify,
  renderAvailabilityDoc,
  renderAvailabilityModule,
} from './lib/custody-availability.mjs'
import { readCapabilityData } from './lib/custody-docs.mjs'
import { mergeSurface, summarize } from './lib/custody-merge.mjs'
import { collectRoutes, renderRoutes } from './lib/custody-routes.mjs'
import { SURFACES, loadCustodySpecs } from './lib/custody-specs.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

/** The banner the openapi-typescript CLI writes; kept so output is unchanged. */
const TYPES_BANNER = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`

const OUTPUTS = {
  public: {
    types: 'src/generated/custody.ts',
    routes: 'src/generated/custody-routes.ts',
    constName: 'CUSTODY_ROUTES',
    typesModule: './custody.js',
    consumer: 'CustodyApi.call',
    defineRouteType: true,
  },
  internal: {
    types: 'src/generated/custody-internal.ts',
    routes: 'src/generated/custody-internal-routes.ts',
    constName: 'CUSTODY_INTERNAL_ROUTES',
    typesModule: './custody-internal.js',
    consumer: 'CustodyInternalApi.call',
    defineRouteType: false,
  },
}

function write(relativePath, content) {
  const path = join(ROOT, relativePath)
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, content)
}

async function main() {
  const specs = loadCustodySpecs(ROOT)
  const merged = {}
  for (const surface of SURFACES) {
    const surfaceSpecs = specs.filter((spec) => spec.surface === surface)
    if (surfaceSpecs.length === 0) {
      throw new Error(`No ${surface} Custody spec is vendored`)
    }
    const { doc, report } = mergeSurface(surfaceSpecs)
    merged[surface] = doc

    const out = OUTPUTS[surface]
    write(out.types, TYPES_BANNER + astToString(await openapiTS(doc)))
    const { entries, skipped } = collectRoutes(doc)
    write(out.routes, renderRoutes(entries, out))

    console.log(summarize(surface, report))
    console.log(
      `${out.routes}: ${entries.length} operations` +
        (skipped > 0 ? ` (${skipped} skipped — no operationId)` : ''),
    )
  }

  const classification = classify(readCapabilityData(ROOT), specs, merged)
  write(
    'src/generated/custody-availability.ts',
    renderAvailabilityModule(classification),
  )
  write('docs/custody-endpoints.md', renderAvailabilityDoc(classification))
}

main().catch((err) => {
  console.error(err.message)
  process.exit(1)
})
