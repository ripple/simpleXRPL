// Renders a Ripple Custody route map: each operationId → its HTTP method and
// path template. This is the runtime companion to the generated `operations`
// types (openapi-typescript emits types only), used by `CustodyApi.call` and
// `CustodyInternalApi.call` to resolve a request.
//
// Custody uses a single credential for every endpoint, so — unlike Palisade —
// there is no per-tag auth scope: the route carries only method + path.

const METHODS = ['get', 'post', 'put', 'patch', 'delete']

/**
 * Collect the routable operations of a document.
 *
 * @returns `{ entries, skipped }` — `[operationId, METHOD, path]` sorted by id,
 *   and how many operations had no operationId.
 * @throws on a duplicate operationId (it would collide in the route map).
 */
export function collectRoutes(doc) {
  const entries = []
  const seen = new Set()
  let skipped = 0
  for (const [path, item] of Object.entries(doc.paths ?? {})) {
    for (const method of METHODS) {
      const op = item?.[method]
      if (op === undefined) continue
      // openapi-typescript keys `operations` off operationId, so an operation
      // without one is neither typed by name nor routable.
      if (op.operationId === undefined) {
        skipped += 1
        continue
      }
      if (seen.has(op.operationId)) {
        throw new Error(
          `Duplicate operationId '${op.operationId}' (at ${method.toUpperCase()} ${path}); ` +
            'operationIds must be unique to key the route map.',
        )
      }
      seen.add(op.operationId)
      entries.push([op.operationId, method.toUpperCase(), path])
    }
  }
  entries.sort((a, b) => a[0].localeCompare(b[0]))
  return { entries, skipped }
}

/**
 * Render a route-map module.
 *
 * @param entries - From {@link collectRoutes}.
 * @param options.constName - The exported constant (e.g. `CUSTODY_ROUTES`).
 * @param options.typesModule - The sibling types module (e.g. `./custody.js`).
 * @param options.consumer - Who reads the map (for the header).
 * @param options.defineRouteType - Emit the `CustodyRoute` interface here;
 *   otherwise import it from ./custody-routes.js.
 */
export function renderRoutes(
  entries,
  { constName, typesModule, consumer, defineRouteType },
) {
  const body = entries
    .map(
      ([id, method, path]) =>
        `  ${JSON.stringify(id)}: { method: '${method}', path: '${path}' },`,
    )
    .join('\n')
  const routeType = defineRouteType
    ? `export interface CustodyRoute {
  readonly method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE'
  readonly path: string
}`
    : `import type { CustodyRoute } from './custody-routes.js'`
  return `/**
 * This file was auto-generated by scripts/gen-custody-types.mjs.
 * Do not make direct changes to the file. Regenerate with \`npm run typegen\`.
 *
 * Each Ripple Custody operationId → its HTTP method and path template (the
 * runtime companion to the \`operations\` types in ${typesModule}). Consumed by
 * \`${consumer}\`.
 */

${routeType}

export const ${constName} = {
${body}
} as const satisfies Record<string, CustodyRoute>
`
}
