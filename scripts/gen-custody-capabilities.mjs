// Generates the per-version Ripple Custody capability table from the vendored
// openapi/custody/capabilities.json. A pinned `apiVersion` gates calls against
// this table; auto-detection reads the live instance spec instead. Regenerated
// by `npm run typegen`, so it never drifts from the vendored data.
//
// Output: src/generated/custody-capabilities.ts

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { readCapabilityData } from './lib/custody-docs.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const data = readCapabilityData(ROOT)
const versions = Object.keys(data)
if (versions.length === 0) {
  throw new Error('openapi/custody/capabilities.json is missing or empty')
}

const out = `/**
 * This file was auto-generated by scripts/gen-custody-capabilities.mjs.
 * Do not make direct changes to the file. Regenerate with \`npm run typegen\`.
 *
 * What each Ripple Custody version supports, from the spec the Custody docs
 * publish for it: endpoints (\`METHOD /path\`), native XRPL operation types, and
 * intent payload types. Consumed by a pinned \`apiVersion\`.
 */

/** A Ripple Custody version with bundled capability data. */
export type KnownCustodyVersion =
${versions.map((v) => `  | ${JSON.stringify(v)}`).join('\n')}

export interface CustodyCapabilityEntry {
  readonly endpoints: readonly string[]
  readonly xrplOperations: readonly string[]
  readonly intentTypes: readonly string[]
}

// Annotated rather than \`as const\`: the literal type would be too large to
// emit into the declaration file, and consumers only feed these into Sets.
export const CUSTODY_CAPABILITIES: Record<
  KnownCustodyVersion,
  CustodyCapabilityEntry
> = ${JSON.stringify(data, null, 2)}
`

writeFileSync(join(ROOT, 'src/generated/custody-capabilities.ts'), out)
console.log(`custody-capabilities.ts: ${versions.length} versions`)
